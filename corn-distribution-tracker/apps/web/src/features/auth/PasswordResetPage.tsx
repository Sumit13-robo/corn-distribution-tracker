import { useEffect, useState, type FormEvent } from "react";
import { Link, useNavigate, useSearchParams } from "react-router-dom";
import { api } from "../../lib/api-client";
import { restoreSession } from "../../lib/session";
import { FormField } from "../../components/common/FormField";
import { AuthLayout } from "./AuthLayout";

export type ResetMode = "forgot" | "reset" | "invite" | "change";

type FieldName = "email" | "token" | "displayName" | "password" | "currentPassword";
type FieldErrors = Partial<Record<FieldName, string>>;

const VALID_MODES: ResetMode[] = ["forgot", "reset", "invite", "change"];

/**
 * All account-recovery flows in one focused screen:
 *  - `forgot`: record a reset request for an operator (this deployment has no
 *    outbound mail, so an administrator still delivers the link securely),
 *  - `reset`: set a new password with a one-time token,
 *  - `invite`: accept an invitation and choose an initial password,
 *  - `change`: signed-in password change for a required reset.
 * Results never reveal whether an account exists.
 */
export function PasswordResetPage() {
  const [params, setParams] = useSearchParams();
  const navigate = useNavigate();
  const requestedMode = params.get("mode") as ResetMode | null;
  const mode: ResetMode = requestedMode && VALID_MODES.includes(requestedMode) ? requestedMode : "forgot";
  const urlToken = params.get("token") ?? "";
  const [email, setEmail] = useState("");
  const [token, setToken] = useState("");
  const [password, setPassword] = useState("");
  const [displayName, setDisplayName] = useState("");
  const [currentPassword, setCurrentPassword] = useState("");
  const [showPassword, setShowPassword] = useState(false);
  const [fieldErrors, setFieldErrors] = useState<FieldErrors>({});
  const [notice, setNotice] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [pending, setPending] = useState(false);

  // Links generated by the invitation/reset APIs embed the token in the URL.
  useEffect(() => {
    if (urlToken && (mode === "reset" || mode === "invite")) setToken(urlToken);
  }, [urlToken, mode]);

  function setMode(next: ResetMode) {
    setParams({ mode: next });
    setFieldErrors({});
    setError(null);
    setNotice(null);
  }

  function clearField(name: FieldName) {
    if (fieldErrors[name]) setFieldErrors((current) => ({ ...current, [name]: undefined }));
  }

  function validate(): FieldErrors {
    const errors: FieldErrors = {};
    if (mode === "forgot") {
      if (!email.trim()) errors.email = "Enter your email address.";
      else if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email.trim())) errors.email = "Enter a valid email address.";
      return errors;
    }
    if ((mode === "reset" || mode === "invite") && token.trim().length < 10) {
      errors.token = "Paste the full one-time token from your link.";
    }
    if (mode === "invite" && !displayName.trim()) errors.displayName = "Enter your name as it should appear to admins.";
    if (mode === "change" && !currentPassword) errors.currentPassword = "Enter your current password.";
    if (password.length < 12) errors.password = "Use at least 12 characters.";
    return errors;
  }

  function submit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    const errors = validate();
    setFieldErrors(errors);
    if (Object.keys(errors).length > 0) return;

    setError(null);
    setNotice(null);
    setPending(true);
    void (async () => {
      try {
        if (mode === "forgot") {
          const ack = await api.forgotPassword(email.trim());
          setNotice(ack.message);
        } else if (mode === "reset") {
          const ack = await api.resetPassword(token.trim(), password);
          setNotice(ack.message);
        } else if (mode === "invite") {
          await api.acceptInvitation(token.trim(), password, displayName.trim());
          setNotice("Invitation accepted. Sign in with your new password.");
        } else {
          const ack = await api.changePassword(currentPassword, password);
          setNotice(ack.message);
          await restoreSession();
        }
        setPending(false);
      } catch (err) {
        setError(err instanceof Error ? err.message : "The request could not be completed. Try again.");
        setPending(false);
      }
    })();
  }

  const content = {
    forgot: {
      eyebrow: "Account recovery",
      title: "Password help",
      intro: (
        <>
          This deployment does not send email. Record a reset request for your administrator, then ask them for a
          one-time link through your organization&rsquo;s secure channel.
        </>
      ),
    },
    reset: {
      eyebrow: "One-time link",
      title: "Set a new password",
      intro: "Paste the token from your reset link. It can be used once and expires after one hour.",
    },
    invite: {
      eyebrow: "Secure invitation",
      title: "Accept your invitation",
      intro: "Choose your display name and a password with at least 12 characters. Your invitation token is embedded in the link.",
    },
    change: {
      eyebrow: "Account security",
      title: "Choose a new password",
      intro: "Confirm your current password, then choose one with at least 12 characters. Other sessions will be signed out.",
    },
  }[mode];

  function secondaryAction() {
    if (mode === "forgot") {
      return (
        <>
          <button type="button" className="text-link" onClick={() => setMode("reset")}>
            I already have a reset token
          </button>
          <Link to="/login">Back to sign in</Link>
        </>
      );
    }
    if (mode === "change") {
      return (
        <button type="button" className="text-link" onClick={() => navigate("/")}>
          Return to workspace
        </button>
      );
    }
    return (
      <>
        <button type="button" className="text-link" onClick={() => setMode("forgot")}>
          Request a new link
        </button>
        <Link to="/login">Back to sign in</Link>
      </>
    );
  }

  return (
    <AuthLayout eyebrow={content.eyebrow} title={content.title} intro={content.intro}>
      {error ? (
        <div className="auth-alert" role="alert">
          <strong>Could not continue</strong>
          <span>{error}</span>
        </div>
      ) : null}

      {notice ? (
        <div className="auth-success" role="status">
          <span className="auth-success-mark" aria-hidden="true">
            ✓
          </span>
          <div>
            <strong>{mode === "forgot" ? "Request recorded" : "All set"}</strong>
            <p>{notice}</p>
          </div>
        </div>
      ) : null}

      {!notice ? (
        <form className="auth-form" onSubmit={submit} noValidate>
          {mode === "forgot" ? (
            <FormField id="reset-email" label="Email" required error={fieldErrors.email}>
              {(ids) => (
                <input
                  id="reset-email"
                  type="email"
                  inputMode="email"
                  autoComplete="email"
                  autoFocus
                  value={email}
                  aria-invalid={fieldErrors.email ? true : undefined}
                  aria-describedby={ids.describedBy || undefined}
                  onChange={(event) => {
                    setEmail(event.target.value);
                    clearField("email");
                  }}
                  disabled={pending}
                />
              )}
            </FormField>
          ) : (
            <>
              {mode === "change" ? (
                <FormField
                  id="current-password"
                  label="Current password"
                  required
                  error={fieldErrors.currentPassword}
                >
                  {(ids) => (
                    <input
                      id="current-password"
                      type="password"
                      autoComplete="current-password"
                      autoFocus
                      value={currentPassword}
                      aria-invalid={fieldErrors.currentPassword ? true : undefined}
                      aria-describedby={ids.describedBy || undefined}
                      onChange={(event) => {
                        setCurrentPassword(event.target.value);
                        clearField("currentPassword");
                      }}
                      disabled={pending}
                    />
                  )}
                </FormField>
              ) : null}

              {mode !== "change" ? (
                <FormField
                  id="reset-token"
                  label="One-time token"
                  required
                  error={fieldErrors.token}
                  helper="Usually filled automatically when you open the link."
                >
                  {(ids) => (
                    <input
                      id="reset-token"
                      type="text"
                      autoComplete="one-time-code"
                      autoFocus={!urlToken}
                      value={token}
                      aria-invalid={fieldErrors.token ? true : undefined}
                      aria-describedby={ids.describedBy || undefined}
                      onChange={(event) => {
                        setToken(event.target.value);
                        clearField("token");
                      }}
                      disabled={pending}
                    />
                  )}
                </FormField>
              ) : null}

              {mode === "invite" ? (
                <FormField id="display-name" label="Display name" required error={fieldErrors.displayName}>
                  {(ids) => (
                    <input
                      id="display-name"
                      type="text"
                      autoComplete="name"
                      autoFocus={Boolean(urlToken)}
                      value={displayName}
                      aria-invalid={fieldErrors.displayName ? true : undefined}
                      aria-describedby={ids.describedBy || undefined}
                      onChange={(event) => {
                        setDisplayName(event.target.value);
                        clearField("displayName");
                      }}
                      disabled={pending}
                    />
                  )}
                </FormField>
              ) : null}

              <FormField
                id="new-password"
                label={mode === "change" ? "New password" : "Password"}
                required
                error={fieldErrors.password}
                helper="At least 12 characters. A passphrase is easiest to remember."
              >
                {(ids) => (
                  <div className="password-control">
                    <input
                      id="new-password"
                      type={showPassword ? "text" : "password"}
                      autoComplete="new-password"
                      value={password}
                      aria-invalid={fieldErrors.password ? true : undefined}
                      aria-describedby={ids.describedBy || undefined}
                      onChange={(event) => {
                        setPassword(event.target.value);
                        clearField("password");
                      }}
                      disabled={pending}
                    />
                    <button
                      type="button"
                      className="password-toggle"
                      aria-controls="new-password"
                      aria-pressed={showPassword}
                      onClick={() => setShowPassword((visible) => !visible)}
                      disabled={pending}
                    >
                      {showPassword ? "Hide" : "Show"}
                    </button>
                  </div>
                )}
              </FormField>
            </>
          )}

          <button type="submit" className="btn auth-submit" disabled={pending}>
            {pending ? (
              <>
                <span className="spinner" aria-hidden="true" /> Working…
              </>
            ) : mode === "forgot" ? (
              "Record reset request"
            ) : mode === "change" ? (
              "Update password"
            ) : mode === "invite" ? (
              "Accept invitation"
            ) : (
              "Set password"
            )}
          </button>
        </form>
      ) : null}

      <nav className="auth-secondary" aria-label="Other password options">
        {secondaryAction()}
      </nav>

      {pending ? (
        <p role="status" className="sr-only">
          Working. Please wait.
        </p>
      ) : null}
    </AuthLayout>
  );
}
